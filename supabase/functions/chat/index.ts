import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

const APRONIX_CONTEXT = `You are Apronix's friendly AI assistant. Apronix is a professional website building agency based in New Delhi, Delhi NCR, India.

Key Information:
- Contact Email: Shayaan.alam111@gmail.com
- Phone/WhatsApp: +91 9958143483
- Location: New Delhi, Delhi NCR, India

Services we offer:
1. UI/UX Design - Beautiful, intuitive designs
2. Web Development - Custom-built websites with clean code
3. Responsive Design - Pixel-perfect across all devices
4. Performance Optimization - Lightning-fast loading
5. SEO Optimization - Boost visibility and rankings
6. Maintenance & Support - Ongoing updates and support

Pricing (approximate):
- Basic Website: ₹15,000 - ₹30,000
- Business Website: ₹30,000 - ₹75,000
- E-commerce Store: ₹50,000 - ₹1,50,000
- Custom Web App: ₹1,00,000+

Be helpful, professional, and encourage users to contact us for detailed quotes. Keep responses concise and friendly. If someone asks about starting a project, encourage them to fill out our enquiry form or contact us directly.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    console.log("Processing chat request with", messages.length, "messages");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [
          { role: "system", content: APRONIX_CONTEXT },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limits exceeded, please try again later." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "Service temporarily unavailable." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      
      return new Response(JSON.stringify({ error: "AI service error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    console.log("Streaming response from AI gateway");
    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (error) {
    console.error("Chat function error:", error);
    return new Response(JSON.stringify({ error: error instanceof Error ? error.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
